export const namespace = 'translation';
export const referenceKeyCount = Object.keys(en).length;

/** Reported by the platform-admin localization screen. */
export function completenessOf(locale: string): number {
  const entry = resources[locale];
  if (!entry) return 0;
  const translated = Object.values(entry.translation).filter((v) => v.trim().length > 0).length;
  return Math.round((translated / referenceKeyCount) * 100);
}
