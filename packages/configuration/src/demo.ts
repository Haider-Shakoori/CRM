/**
 * Demonstration-content policy and shared honest-labelling copy.
 *
 * Every string in this file exists for one reason: the frontend must never imply that
 * an unimplemented capability is real. Components import these labels instead of
 * inventing their own wording, so the message stays consistent everywhere.
 */

